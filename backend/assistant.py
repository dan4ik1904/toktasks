def _has(low: str, *words: str) -> bool:
    """Точное вхождение слова: короткие — по границам, длинные — подстрокой."""
    pad = f" {low} "
    for w in words:
        w = w.replace("ё", "е").strip()
        if not w:
            continue
        if len(w) < 5:
            if f" {w} " in pad:
                return True
        elif w in low:
            return True
    return False


def _pack(pair: tuple[str, str], lang: str) -> dict:
    tt, ru = pair
    say = tt.replace("«", "").replace("»", "")
    return {"reply": f"{tt} ({ru})", "say": say, "lang": lang}


def _hit(inner: tuple[str, str], topic: int | None, lang: str) -> dict:
    if topic is not None and OFFLINE_QA[topic][1] == inner[0]:
        return _pack(_practice(inner), lang)
    return _pack(inner, lang)


