def _intent_diff(low: str) -> tuple[str, str] | None:
    if not any(p in low for p in _DIFF_PATTERNS):
        return None
    for keys, tt, ru in _DIFFS:
        if all(k in low for k in keys):
            return tt, ru
    return (
        "Кайсы сүзләрне чагыштырабыз? Әйт әле!",
        "Какие слова сравниваем? Напиши оба — мәсәлән: «в чём разница исәнме и исәнмесез», и я разберу!",
    )


