def _intent_make(low: str, lang: str) -> tuple[str, str]:
    for keys, tts, rus in _MAKE_SETS:
        if any(k in low for k in keys):
            tt = " ".join(f"«{s}»" for s in tts)
            ru = "Три фразы — повторяй за мной: " + "; ".join(
                f"«{t}» — {r}" for t, r in zip(tts, rus)
            ) + "."
            return tt, ru
    tts = ("Минем исемем …!", "Синең исемең ничек?", "Шатмын!")
    tt = " ".join(f"«{s}»" for s in tts)
    ru = (
        "Три фразы для знакомства — повторяй за мной: «Минем исемем …!» — «Меня зовут …!»; "
        "«Синең исемең ничек?» — «А тебя как зовут?»; «Шатмын!» — «Рад знакомству!». "
        "Отработай их на острове Сәлам!"
    )
    return tt, ru


def _ask_offline(message: str, lang: str) -> dict:
    low = _norm(message)
    if not low:
        tt = "Сора әле! Татарча да, русча да аңлыйм."
        ru = "Спроси что-нибудь про татарский — слово, фразу или правило. Понимаю и русский, и татарский!"
        return {"reply": f"{tt} ({ru})", "say": tt, "lang": lang}

    # «В чём разница…» — разбираем раньше словаря, иначе сработает отдельное слово.
    if any(p in low for p in _DIFF_PATTERNS):
        for keys, dtt, dru in _DIFFS:
            if all(k in low for k in keys):
                return {"reply": f"{dtt} ({dru})", "say": dtt, "lang": lang}

    hit = _match_qa(low)
    if hit:
        tt, ru = hit
        return {"reply": f"{tt} ({ru})", "say": tt, "lang": lang}

    if any(p in low for p in _HOW_PATTERNS + _MEAN_PATTERNS):
        phrase = _extract_phrase(low, _HOW_PATTERNS + _MEAN_PATTERNS)
        if phrase:
            inner = _match_qa(phrase)
            if inner:
                tt, ru = inner
                return {"reply": f"{tt} ({ru})", "say": tt, "lang": lang}
            tt = "Анысын әлегә белмим, тик «Рәхмәт!» — беләм!"
            ru = (
                f"«{phrase}» — этого я пока не знаю (Ярдәмче ещё учится). "
                "Но «спасибо» — «Рәхмәт!» — знаю точно! Спроси про приветствия, числа, семью или еду."
            )
            return {"reply": f"{tt} ({ru})", "say": tt, "lang": lang}

    diff = _intent_diff(low)
    if diff:
        tt, ru = diff
        return {"reply": f"{tt} ({ru})", "say": tt, "lang": lang}

    if any(p in low for p in _MAKE_PATTERNS):
        tt, ru = _intent_make(low, lang)
        return {"reply": f"{tt} ({ru})", "say": tt, "lang": lang}

    if lang == "tt":
        tt, ru = OFFLINE_FALLBACK_TT_FULL, OFFLINE_FALLBACK_RU
    else:
        tt, ru = OFFLINE_FALLBACK_TT, OFFLINE_FALLBACK_RU
    return {"reply": f"«{tt}» — {ru}" if lang == "ru" else f"{tt} {ru}", "say": tt, "lang": lang}


async def ask_assistant(message: str) -> dict:
    """Главный вход: всегда словарь {reply, say, lang}."""
    message = message.strip()
    lang = detect_lang(message) if message else "ru"
    if LLM_AVAILABLE:
        judged = await _ask_llm(message, lang)
        if judged:
            return judged
    return _ask_offline(message, lang)


async def _ask_llm(message: str, lang: str) -> dict | None:
    url = settings.llm_base_url.rstrip("/") + "/chat/completions"
    try:
        async with httpx.AsyncClient(timeout=30) as client:
            resp = await client.post(
                url,
                headers={"Authorization": f"Bearer {settings.llm_api_key}"},
                json={
                    "model": settings.llm_model,
                    "messages": [
                        {"role": "system", "content": SYSTEM_PROMPT},
                        {
                            "role": "user",
                            "content": f"[язык ученика: {'татарский' if lang == 'tt' else 'русский'}] {message}",
                        },
                    ],
                    "temperature": 0.7,
                    "max_tokens": 400,
                },
            )
            resp.raise_for_status()
            text = resp.json()["choices"][0]["message"]["content"]
        start, end = text.find("{"), text.rfind("}")
        data = json.loads(text[start : end + 1])
        tt = str(data.get("tt") or "").strip()
        ru = str(data.get("ru") or "").strip()
        if not tt:
            return None
        reply = f"{tt} ({ru})" if ru else tt
        return {"reply": reply, "say": tt, "lang": lang}
    except Exception:
        # LLM упал посреди диалога — деградируем в офлайн-режим.
        return None


