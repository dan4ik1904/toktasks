def _topic_of(history: list[dict]) -> int | None:
    """Индекс словарной темы последнего ответа духа (смена темы — новый разговор)."""
    for m in reversed(history or []):
        if m.get("role") != "assistant":
            continue
        text = m.get("text", "")
        for i, (_keys, tt, _ru) in enumerate(OFFLINE_QA):
            if tt and tt in text:
                return i
    return None


def _syl_words(say: str) -> list[str]:
    out = []
    for w in re.sub(r"[«»\"'.,!?—–:;()]", " ", say).split()[:4]:
        out.append("-".join(split_syllables(w)))
    return out


