def detect_lang(text: str) -> str:
    """tt, если есть татарские буквы или явные татарские слова; иначе ru."""
    low = text.lower()
    if any(ch in TT_LETTERS for ch in text):
        return "tt"
    tt_markers = (
        "ничек", "нәрсә", "кайда", "кайчан", "ничә", "кем", "нинди", "кайсы",
        "әйе", "юк", "татарча", "әйт", "сөйлә", "аңла", "бул", "мин", "син",
        "сез", "без", "алар", "ул", "исәнме", "сәлам", "рәхмәт", "сау бул",
    )
    if any(m in low for m in tt_markers):
        return "tt"
    return "ru"


def _norm(text: str) -> str:
    return text.lower().replace("ё", "е").strip()


def _match_qa(low: str) -> tuple[str, str] | None:
    """Лучшее совпадение из словаря: побеждает самый длинный ключ."""
    best: tuple[int, str, str] | None = None
    for keys, tt, ru in OFFLINE_QA:
        for key in keys:
            if len(key) < 4:
                hit = f" {key} " in f" {low} " or low == key
            else:
                hit = key in low
            if hit and (best is None or len(key) > best[0]):
                best = (len(key), tt, ru)
    return (best[1], best[2]) if best else None


