def _extract_phrase(low: str, patterns: tuple[str, ...]) -> str:
    text = low
    for p in patterns:
        text = text.replace(p, " ")
    text = re.sub(r"[«»\"'.,!?—–:;()]", " ", text)
    words = [w for w in text.split() if w not in _STRIP_WORDS]
    return " ".join(words).strip()


