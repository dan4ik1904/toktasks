// Очки за правильный ответ в зависимости от серии
export function pointsForStreak(streak: number): number {
  if (streak >= 20) return 50; // x5 + особое сообщение
  if (streak >= 10) return 30; // x3
  if (streak >= 5) return 20; // x2
  return 10; // базовые
}

export function streakMessage(streak: number): string | null {
  if (streak === 5) return "🔥 Серия x2! Так держать!";
  if (streak === 10) return "⚡ Серия x3! Син — йолдыз!";
  if (streak === 20) return "👑 Легенда! Серия x5!";
  if (streak > 20 && streak % 10 === 0) return `🌟 ${streak} подряд! Ту-ты-ты-ты!`;
  return null;
}
